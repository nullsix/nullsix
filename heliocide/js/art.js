// HELIOCIDE — ASCII creature art. DATA ONLY. Imports nothing (same layering law as cards.js).
//
// One hand-authored piece per card id in cards.js, plus a `default` fallback. The UI renders
// these in a <pre> with the card's type gradient painted through the glyphs
// (`background-clip: text`), at full size in the zoom overlay and the gallery and as a faint
// 3px texture in the art window of a board card. The sigil SVGs in ui.js remain the other half
// of the art toggle — neither mode is the fallback for the other.
//
// HARD RULES (test/ui-smoke.mjs and the authoring pipeline both check these):
//   * printable ASCII only, code points 32-126. No box drawing, no unicode, no emoji — iOS
//     substitutes anything outside this range into a proportional or colour-emoji font and the
//     grid tears apart.
//   * every piece is exactly 32 columns x 16 rows. One uniform aspect means one font-size
//     per card size works for the whole catalog, and the block centres exactly. The CSS
//     renders cells at the classic 1:2 terminal aspect (line-height 1.2 on `.ascii`), so
//     32x16 lands as a square plate — author and preview at editor-normal line spacing.
//   * no trailing whitespace on any line (so the widest line — always the full-width frame
//     rule — sets `max-content` and the piece centres honestly).
//   * the first and last line of every piece is its type's 32-char frame rule: a symmetric
//     density ramp, in the density order `. , : ; - = + * # % @`. Bone ramps to bone, ember
//     banks its coals, rot rots, gold coins itself, song runs a wave through it.
//
// Read them small. They are drawn to hold a silhouette at a glance — crystal bloom, sealed
// rock, gaunt hound, bone bench, mote, sow, geode, drake, creeper, hedge, cliff-drip, maw,
// fork, chained pup, squat brick, coil, crystal, lamp, storm rank, ice dragon — with the
// cover's art-deco bones: hard symmetry, ray fans, triangles.

